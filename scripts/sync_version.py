"""
Синхронизирует все «потребители» версии с `core/__version__.py`.

Запуск:
    python scripts/sync_version.py

Что делает:
  • Перезаписывает `version_info.txt` (используется PyInstaller'ом для
    Windows-resource блока внутри TranslateX.exe).
  • setup.iss НЕ трогаем: он читает версию через `GetFileVersion()` из
    скомпилированного TranslateX.exe → транзитивно подхватит обновлённую
    версию автоматически.

Запускается:
  • вручную после bump'а версии в `core/__version__.py`,
  • автоматически из `build.bat` перед pyinstaller (см. workflow /build).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.__version__ import __version__, __version_tuple__  # noqa: E402


VERSION_INFO_TEMPLATE = """# UTF-8
#
# Auto-generated by scripts/sync_version.py — DO NOT EDIT MANUALLY.
# Source of truth: core/__version__.py
#
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={tup},
    prodvers={tup},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          u'040904B0',
          [StringStruct(u'CompanyName',      u'TranslateX'),
           StringStruct(u'FileDescription',  u'Real-time screen translation overlay'),
           StringStruct(u'FileVersion',      u'{ver4}'),
           StringStruct(u'InternalName',     u'TranslateX'),
           StringStruct(u'LegalCopyright',   u'Copyright 2026 TranslateX'),
           StringStruct(u'OriginalFilename', u'TranslateX.exe'),
           StringStruct(u'ProductName',      u'TranslateX'),
           StringStruct(u'ProductVersion',   u'{ver}')])
      ]
    ),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
"""


def write_version_info() -> Path:
    target = ROOT / "version_info.txt"
    ver4 = ".".join(str(x) for x in __version_tuple__)
    content = VERSION_INFO_TEMPLATE.format(
        tup=__version_tuple__,
        ver=__version__,
        ver4=ver4,
    )
    target.write_text(content, encoding="utf-8")
    return target


def main() -> None:
    print(f"[sync_version] __version__ = {__version__}")
    p = write_version_info()
    print(f"[sync_version] wrote {p}")
    print("[sync_version] setup.iss reads version dynamically via GetFileVersion() — no action.")


if __name__ == "__main__":
    main()
